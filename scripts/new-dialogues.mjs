export function generateNewDialogues(markdown) {
  const body = markdown.split("# 新規追加セリフ（文法事項別）")[1];
  if (!body) throw new Error("新規セリフの本文がありません");
  const dialogues = [];
  let section = 0;
  let row = 0;
  for (const line of body.split(/\r?\n/)) {
    const heading = line.match(/^### (\d+)\./);
    if (heading) {
      section = Number(heading[1]);
      row = 0;
    }
    const match = line.match(/^\| (\d+) \| ([^|]+) \| ([^|]+) \|$/);
    if (!match) continue;
    const [, triggerCode, rawChinese, rawJapanese] = match;
    const zhHans = rawChinese.trim();
    const ja = rawJapanese.trim();
    const learning = (grammarNotes[section - 1] ?? []).map((note) => {
      const [phrase, role, meaning] = note.split("|");
      return { phrase, role, meaning };
    }).filter((note) => zhHans.includes(note.phrase));
    if (zhHans === "我老师会生气的！") {
      learning.find((note) => note.phrase === "的").meaning = "文末に置いて、そうなるという確信を表す";
    }
    if (!learning.length) throw new Error(`新規セリフ${section}-${row + 1}に学習解説がありません`);
    if (triggerCode === "33" && !conditions[zhHans]) {
      throw new Error(`方向条件が未定義です: ${zhHans}`);
    }
    const dialogue = {
      id: `additional-2026-10-29-${section}-${++row}`,
      triggerCode, zhHans, ja, learning,
    };
    if (conditions[zhHans]) dialogue.condition = conditions[zhHans];
    dialogues.push(dialogue);
  }
  if (dialogues.length !== 182) throw new Error("新規セリフは182件必要です");
  return dialogues;
}
