func japaneseRole(for tag: NLTag?, token: String) -> String {
  if let role = roleOverrides[token] { return role }
  switch tag?.rawValue {
  case "Noun", "PlaceName", "PersonalName", "OrganizationName": return "名詞"
  case "Verb": return "動詞"
  case "Adjective": return "形容詞"
  case "Adverb": return "副詞"
  case "Pronoun": return "代名詞"
  case "Determiner": return "指示語・限定語"
  case "Particle": return "助詞"
  case "Preposition": return "介詞"
  case "Conjunction": return "接続詞"
  case "Interjection": return "感嘆詞"
  case "Number": return "数詞"
  case "Classifier": return "量詞"
  default: return token.count >= 3 ? "語句・表現" : "語句"
  }
}

