      let id = dialogue["id"] as! String
      let text = (dialogue["text"] as! [String: String])["zhHans"]!
      if let manual = manualAnnotations[id] {
        annotations[id] = manual
        continue
      }

      let tagger = NLTagger(tagSchemes: [.lexicalClass])
      tagger.string = text
      tagger.setLanguage(.simplifiedChinese, range: text.startIndex..<text.endIndex)
      var items: [LearningItem] = []
      tagger.enumerateTags(
        in: text.startIndex..<text.endIndex,
        unit: .word,
        scheme: .lexicalClass,
        options: [.omitWhitespace, .omitPunctuation]
      ) { tag, range in
        let token = String(text[range])
        guard let meaning = termMeanings[token] else {
          missingMeanings.insert(token)
          return true
        }
        items.append([
          "phrase": token,
          "role": japaneseRole(for: tag, token: token),
          "meaning": meaning
        ])
        return true
      }
      annotations[id] = items
