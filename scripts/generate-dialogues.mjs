export function parseLines(markdown) {
  const sections = [];
  let section;
  for (const line of markdown.split(/\r?\n/)) {
    const heading = line.match(/^### (\d+)\. (.+)$/);
    if (heading) {
      section = { code: heading[1], title: heading[2], lines: [] };
      sections.push(section);
    } else if (line.startsWith("## ")) {
      section = undefined;
    } else {
      const item = line.match(/^\d+\\?\.\s+(.+?)(?:〔(.+)〕)?$/);
      if (section && item) section.lines.push({ text: item[1].trim(), grammar: item[2] });
    }
  }
  return sections;
}

const source = new URL("../drafts/lines-translated.md", import.meta.url);
const sections = parseLines(await readFile(source, "utf8"));
if (sections.length !== groups.length) throw new Error("台詞の条件数と翻訳・解説の条件数が一致しません");
const dialogues = sections.flatMap((section, index) => {
  const notes = groups[index];
  if (Number(section.code) !== index + 1 || section.lines.length !== notes.length) {
    throw new Error(`条件${section.code}の台詞数が翻訳・解説と一致しません`);
  }
  return section.lines.map((line, lineIndex) => {
    const [ja, annotation] = notes[lineIndex];
    const learning = annotation.split(";").map((item) => {
      const [phrase, role, meaning] = item.split("|");
      if (!phrase || !role || !meaning) throw new Error(`条件${section.code}の解説が不完全です`);
      return { phrase, role, meaning };
    });
    if (line.grammar) learning.push({ phrase: line.text, role: "文法", meaning: line.grammar });
    const dialogue = {
      id: `translated-${section.code}-${lineIndex + 1}`,
      triggerCode: section.code,
      zhHans: line.text,
      ja,
      learning,
    };
    if (section.code === "14") {
      if ([2, 5].includes(lineIndex)) dialogue.condition = "player-white";
      if ([3, 4].includes(lineIndex)) dialogue.condition = "player-black";
    }
    if (section.code === "20" && lineIndex === 1) dialogue.condition = "queen-returned";
    return dialogue;
  });
});
const newSource = new URL("../drafts/chinese_chess_new_dialogues_182_2026-10-29.md", import.meta.url);
const additional = generateNewDialogues(await readFile(newSource, "utf8"));
for (const [filename, lines] of [
  ["lines-translated.json", dialogues],
  ["lines-additional-2026-10-29.json", additional],
]) {
  const output = new URL(`../app/data/${filename}`, import.meta.url);
  const content = `${JSON.stringify(lines, null, 2)}\n`;
  if (process.argv.includes("--check")) {
    if (await readFile(output, "utf8") !== content) throw new Error("npm run dialogues:generate を実行してください");
    console.log(`Verified ${lines.length} dialogues in ${filename}.`);
  } else {
    await mkdir(new URL("../app/data/", import.meta.url), { recursive: true });
    await writeFile(output, content);
    console.log(`Generated ${lines.length} dialogues in ${filename}.`);
  }
}
